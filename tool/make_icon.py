"""Generates SonaPlay's icon from one geometry: docs/icon/icon.svg plus the
Android adaptive icon layers and the notification icon.

Run from the project root: python tool/make_icon.py
PNGs (legacy mipmaps, Play Store 512px) are rendered from icon.svg separately.
"""
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "android/app/src/main/res"

# Palette: the app's default accent (#7C5CFF) between lilac and cyan
LILAC, VIOLET, CYAN = "#C4B5FD", "#7C5CFF", "#22D3EE"
BG_CENTER, BG_EDGE = "#2A1D63", "#0B0B0F"
PLAY = "#E9E3FF"
SCALE = 1.12  # foreground scale around the center of the 108 canvas


def _pt(cx, cy, r, deg):
    a = math.radians(deg)
    return round(cx + r * math.cos(a), 2), round(cy + r * math.sin(a), 2)


def _arc(cx, cy, r, a0, a1):
    (x0, y0), (x1, y1) = _pt(cx, cy, r, a0), _pt(cx, cy, r, a1)
    return f"M{x0},{y0} A{r},{r} 0 0 1 {x1},{y1}"


# S from two bowls: the upper opens right (around the play), the lower opens left
S_PATH = "M63.09,38.25 A10.5,10.5 0 1 0 54,54 A10.5,10.5 0 1 1 44.91,69.75"
PLAY_PATH = "M53.9,40.3 L59.6,43.6 L53.9,46.9 Z"
# Sound waves: (path, opacity), right of the lower bowl and left of the upper
WAVES = [
    (_arc(54, 64.5, 18.5, -38, 38), 0.85),
    (_arc(54, 64.5, 23.5, -32, 32), 0.45),
    (_arc(54, 43.5, 18.5, 142, 218), 0.85),
    (_arc(54, 43.5, 23.5, 148, 212), 0.45),
]


def svg():
    waves = "\n".join(
        f'    <path d="{d}" fill="none" stroke="url(#s)" stroke-width="3" '
        f'stroke-linecap="round" opacity="{o}"/>'
        for d, o in WAVES
    )
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108" width="108" height="108">
  <defs>
    <radialGradient id="bg" cx="54" cy="50" r="62" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="{BG_CENTER}"/>
      <stop offset="1" stop-color="{BG_EDGE}"/>
    </radialGradient>
    <linearGradient id="s" x1="66" y1="30" x2="42" y2="80" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="{LILAC}"/>
      <stop offset="0.45" stop-color="{VIOLET}"/>
      <stop offset="1" stop-color="{CYAN}"/>
    </linearGradient>
  </defs>
  <rect width="108" height="108" fill="url(#bg)"/>
  <g transform="translate(54 54) scale({SCALE}) translate(-54 -54)">
{waves}
    <path d="{S_PATH}" fill="none" stroke="url(#s)" stroke-width="8.5" stroke-linecap="round"/>
    <path d="{PLAY_PATH}" fill="{PLAY}" stroke="{PLAY}" stroke-width="2" stroke-linejoin="round"/>
  </g>
</svg>
"""


def _gradient():
    return f"""
            <aapt:attr name="android:strokeColor">
                <gradient android:type="linear"
                    android:startX="66" android:startY="30"
                    android:endX="42" android:endY="80">
                    <item android:offset="0" android:color="{LILAC}"/>
                    <item android:offset="0.45" android:color="{VIOLET}"/>
                    <item android:offset="1" android:color="{CYAN}"/>
                </gradient>
            </aapt:attr>"""


def _vector(body, size=108, viewport=108, extra_ns=""):
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/make_icon.py -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"{extra_ns}
    android:width="{size}dp"
    android:height="{size}dp"
    android:viewportWidth="{viewport}"
    android:viewportHeight="{viewport}">
{body}
</vector>
"""


def _group(paths, scale=SCALE):
    return f"""    <group android:pivotX="54" android:pivotY="54"
        android:scaleX="{scale}" android:scaleY="{scale}">
{paths}
    </group>"""


def foreground():
    paths = "".join(
        f"""
        <path android:pathData="{d}" android:strokeWidth="3"
            android:strokeLineCap="round" android:strokeAlpha="{o}">{_gradient()}
        </path>"""
        for d, o in WAVES
    )
    paths += f"""
        <path android:pathData="{S_PATH}" android:strokeWidth="8.5"
            android:strokeLineCap="round">{_gradient()}
        </path>
        <path android:pathData="{PLAY_PATH}" android:fillColor="{PLAY}"
            android:strokeColor="{PLAY}" android:strokeWidth="2"
            android:strokeLineJoin="round"/>"""
    return _vector(_group(paths), extra_ns='\n    xmlns:aapt="http://schemas.android.com/aapt"')


def background():
    return _vector(
        f"""    <path android:pathData="M0,0h108v108h-108z">
        <aapt:attr name="android:fillColor">
            <gradient android:type="radial"
                android:centerX="54" android:centerY="50"
                android:gradientRadius="62">
                <item android:offset="0" android:color="{BG_CENTER}"/>
                <item android:offset="1" android:color="{BG_EDGE}"/>
            </gradient>
        </aapt:attr>
    </path>""",
        extra_ns='\n    xmlns:aapt="http://schemas.android.com/aapt"',
    )


def monochrome(scale=SCALE, size=108):
    """One color shape: themed icons (Android 13+) and the notification icon"""
    paths = "".join(
        f"""
        <path android:pathData="{d}" android:strokeWidth="3"
            android:strokeLineCap="round" android:strokeColor="#FFFFFF"
            android:strokeAlpha="{o}"/>"""
        for d, o in WAVES
    )
    paths += f"""
        <path android:pathData="{S_PATH}" android:strokeWidth="8.5"
            android:strokeLineCap="round" android:strokeColor="#FFFFFF"/>
        <path android:pathData="{PLAY_PATH}" android:fillColor="#FFFFFF"
            android:strokeColor="#FFFFFF" android:strokeWidth="2"
            android:strokeLineJoin="round"/>"""
    return _vector(_group(paths, scale), size=size)


ADAPTIVE = """<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background"/>
    <foreground android:drawable="@drawable/ic_launcher_foreground"/>
    <monochrome android:drawable="@drawable/ic_launcher_monochrome"/>
</adaptive-icon>
"""


if __name__ == "__main__":
    (ROOT / "docs/icon").mkdir(parents=True, exist_ok=True)
    (ROOT / "docs/icon/icon.svg").write_text(svg())
    (RES / "drawable/ic_launcher_foreground.xml").write_text(foreground())
    (RES / "drawable/ic_launcher_background.xml").write_text(background())
    (RES / "drawable/ic_launcher_monochrome.xml").write_text(monochrome())
    # Status bar icon: the shape fills the 24dp box (108 viewport scaled ~1.6)
    (RES / "drawable/ic_notification.xml").write_text(monochrome(scale=1.6, size=24))
    (RES / "mipmap-anydpi-v26").mkdir(exist_ok=True)
    (RES / "mipmap-anydpi-v26/ic_launcher.xml").write_text(ADAPTIVE)
    print("icon written")
